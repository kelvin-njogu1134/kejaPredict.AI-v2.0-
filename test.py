# About section
st.subheader("📊 What is KejaPredict AI?")

st.write("""
KejaPredict AI is a machine learning-based real estate intelligence system that predicts house prices in Kenya using data-driven insights.

It combines scraped property data with geospatial features (latitude and longitude) to understand how location and property characteristics influence pricing.
""")

# Problem section
st.subheader("🚨 Problem It Solves")

st.markdown("""
- ❌ Unclear and inconsistent property pricing in Kenya  
- ❌ Lack of data-driven decision making for buyers and renters  
- ❌ Scattered and unstructured property listings across websites  
- ❌ Location impact on pricing is often ignored  
""")

# Solution section
st.subheader("💡 Solution")

st.markdown("""
KejaPredict AI solves this by:

✔ Scraping real estate data (price, bedrooms, bathrooms, location, property type)  
✔ Cleaning and structuring the dataset  
✔ Using OpenStreetMap API to convert locations into latitude & longitude  
✔ Applying machine learning to predict house prices based on features + location  
""")

# Impact section
st.subheader("🚀 Impact")

st.markdown("""
- 🏡 Helps buyers understand fair market prices  
- 💰 Reduces overpaying for rentals and houses  
- 📊 Assists investors in making data-driven decisions  
- 🏗 Enables better real estate market insights in Kenya  
""")

